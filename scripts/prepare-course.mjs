// Turns a course folder into the files the Angular build reads. Everything it
// writes is generated and gitignored:
//
//   .course/public/             content/, quiz/, favicon and logo, plus the lesson manifest
//   .course/index.html          the page shell, with the course's title and description
//   .course/prism-languages.js  syntax highlighting for the course's code languages
//   src/generated/course.ts     the typed COURSE constant the app imports
//   src/generated/theme.css     brand colours and gradients
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, resolve } from 'node:path';
import { coursePaths, loadCourse, prismComponentFiles, shellRoot } from './course-config.mjs';
import { buildManifest } from './generate-manifest.mjs';

const outDir = resolve(shellRoot, '.course');
const publicDir = resolve(outDir, 'public');
const generatedDir = resolve(shellRoot, 'src', 'generated');
const NOTE = 'Generated by scripts/prepare-course.mjs from the course folder. Do not edit.';

const MIME = { '.ico': 'image/x-icon', '.svg': 'image/svg+xml', '.png': 'image/png' };

/** Writes `content` only when it differs, so a dev server is not woken up for nothing. */
function writeIfChanged(file, content) {
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (existsSync(file) && readFileSync(file).equals(next)) return;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, next);
}

/** Every file under `dir` as a path relative to it, with forward slashes. */
function listFiles(dir, prefix = '') {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const rel = prefix ? `${prefix}/${name}` : name;
    return statSync(resolve(dir, name)).isDirectory() ? listFiles(resolve(dir, name), rel) : [rel];
  });
}

/** Makes `dir` hold exactly `files` (relative path → content): writes changes, removes the rest. */
function mirror(dir, files) {
  for (const [rel, content] of files) writeIfChanged(resolve(dir, rel), content);
  for (const rel of listFiles(dir)) if (!files.has(rel)) rmSync(resolve(dir, rel));
}

const escapeHtml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** The bite mark (a circle with a bite out of it) in the course gradient, as a favicon. */
function biteMarkSvg([a, b, c]) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0%" stop-color="${a}"/><stop offset="50%" stop-color="${b}"/><stop offset="100%" stop-color="${c}"/></linearGradient><mask id="m"><rect width="32" height="32" fill="#fff"/><circle cx="27" cy="6" r="7" fill="#000"/></mask></defs><circle cx="15" cy="17" r="14" fill="url(#g)" mask="url(#m)"/></svg>\n`;
}

function themeCss({ scale, gradient, gradientDark }) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(scale[600].slice(i, i + 2), 16));
  const stops = ([x, y, z]) => `linear-gradient(100deg, ${x} 0%, ${y} 48%, ${z} 100%)`;
  return `/* ${NOTE} */
@theme {
${Object.entries(scale)
  .map(([step, color]) => `  --color-brand-${step}: ${color};`)
  .join('\n')}

  --shadow-glow: 0 8px 22px rgb(${r} ${g} ${b} / 0.26);
}

:root {
  --gradient-brand: ${stops(gradient)};
}
/* Lighter stops in dark mode, so the far end stays readable on ink. */
.dark {
  --gradient-brand: ${stops(gradientDark)};
}
`;
}

/**
 * Prepares the build for the course in `courseDir`. Throws (listing the problems)
 * when course.json is wrong. Returns a few numbers for the log line.
 */
export function prepareCourse(courseDir) {
  const paths = coursePaths(courseDir);
  const course = loadCourse(courseDir);
  const manifest = buildManifest(paths);

  // ---- .course/public: what ends up next to index.html ---------------------
  const files = new Map();
  for (const rel of listFiles(paths.content)) files.set(`content/${rel}`, readFileSync(resolve(paths.content, rel)));
  files.set('content/course-manifest.json', JSON.stringify(manifest, null, 2) + '\n');
  for (const rel of listFiles(paths.quizDir)) files.set(`quiz/${rel}`, readFileSync(resolve(paths.quizDir, rel)));

  const faviconExt = course.brand.favicon ? extname(course.brand.favicon).toLowerCase() : '.svg';
  const faviconName = `favicon${faviconExt}`;
  files.set(
    faviconName,
    course.brand.favicon ? readFileSync(resolve(courseDir, course.brand.favicon)) : biteMarkSvg(course.brand.gradient),
  );
  if (course.brand.logo) files.set('logo.svg', readFileSync(resolve(courseDir, course.brand.logo)));
  mirror(publicDir, files);

  // ---- .course/index.html --------------------------------------------------
  const template = readFileSync(resolve(shellRoot, 'src', 'index.template.html'), 'utf8');
  writeIfChanged(
    resolve(outDir, 'index.html'),
    template
      .replaceAll('%COURSE_NAME%', escapeHtml(course.name))
      .replaceAll('%COURSE_DESCRIPTION%', escapeHtml(course.description))
      .replaceAll('%FAVICON_LINK%', `<link rel="icon" type="${MIME[faviconExt]}" href="${faviconName}">`),
  );

  // ---- .course/prism-languages.js ------------------------------------------
  const components = prismComponentFiles(course.codeLanguages);
  writeIfChanged(
    resolve(outDir, 'prism-languages.js'),
    `/* ${NOTE} */\n` +
      components.map((file) => readFileSync(resolve(shellRoot, 'node_modules', 'prismjs', file), 'utf8')).join(';\n'),
  );

  // ---- src/generated -------------------------------------------------------
  const appConfig = {
    id: course.id,
    name: course.name,
    subject: course.subject,
    description: course.description,
    logo: course.brand.logo ? 'logo.svg' : null,
    gradient: course.brand.gradient,
    home: course.home,
    kinds: course.kinds,
    hasCode: course.codeLanguages.length > 0,
  };
  writeIfChanged(
    resolve(generatedDir, 'course.ts'),
    `// ${NOTE}\nimport type { CourseConfig } from '../app/core/course/course.model';\n\n` +
      `export const COURSE: CourseConfig = ${JSON.stringify(appConfig, null, 2)};\n`,
  );
  writeIfChanged(resolve(generatedDir, 'theme.css'), themeCss(course.brand));

  return {
    name: course.name,
    lessons: manifest.lessons.length,
    topics: manifest.topics.filter((t) => t.count).length,
    languages: components.length,
  };
}
